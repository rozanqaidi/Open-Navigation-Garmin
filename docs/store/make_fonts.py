# Builds docs/store/fonts.js (used by render.html) from the Venu 2 system fonts of the
# LOCAL Connect IQ SDK, so the store screenshots use exactly the watch's own text.
# fonts.js is Garmin's font data: it is in .gitignore and must never be committed.
#
#   python3 docs/store/make_fonts.py
#
# Sources: ~/Library/Application Support/Garmin/ConnectIQ/Devices/venu2/simulator.json
# (fontSet "ww": Connect IQ name -> file, e.g. xtiny -> FNT_006B370300_TINY) and the
# .cft files in ~/Library/Application Support/Garmin/ConnectIQ/Fonts.
#
# .cft layout (worked out from the SDK files, all big-endian):
#   0x0c u32  offset of the glyph table
#   0x16 u16  font height (px), 0x18 u16 ascent, 0x1a u16 descent
#   0x34 u32  number of code point ranges, then per range 3 x u32:
#             [first code point, last code point, first glyph index]
#             (glyph index = first index + (cp - first cp); unknown cp -> glyph 0)
#   glyph table: one 4-byte entry per glyph [b0, b1, b2, advance]:
#             bitmap offset = b2 << 16 | b0 << 8 | b1 (into the decompressed bitmaps)
#   then a zlib stream (starts with 78 9c) with all glyph bitmaps:
#             2-bit grey, 4 px per byte (low bits first); each glyph uses the widest row
#             (a multiple of 4 bytes) that still leaves at least `height` rows.
#   The glyph image's top is the top of the text line; it is drawn at the pen position.
import base64, io, json, os, struct, zlib
from PIL import Image

SDK = os.path.expanduser('~/Library/Application Support/Garmin/ConnectIQ')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fonts.js')
NAMES = ['xtiny', 'tiny', 'small', 'medium', 'large']


class CFT:
    def __init__(self, path):
        f = open(path, 'rb').read()
        u32 = lambda o: struct.unpack('>I', f[o:o + 4])[0]
        u16 = lambda o: struct.unpack('>H', f[o:o + 2])[0]
        self.height = u16(0x16)
        self.ascent = u16(0x18)
        n = u32(0x34)
        o = 0x38
        self.ranges = []
        for _ in range(n):
            self.ranges.append([u32(o), u32(o + 4), u32(o + 8)])
            o += 12
        total = sum(b - a + 1 for a, b, c in self.ranges) + 1
        t1 = u32(0x0c)
        ents = [f[t1 + 4 * i:t1 + 4 * i + 4] for i in range(total)]
        offs = [(e[2] << 16) | (e[0] << 8) | e[1] for e in ents]
        self.adv = [e[3] for e in ents]
        d = zlib.decompress(f[f.find(b'\x78\x9c', t1 + 4 * total):])
        H = self.height
        self.img = []
        for i in range(total):
            size = (offs[i + 1] if i + 1 < total else len(d)) - offs[i]
            rowb = max([r for r in range(4, 65, 4) if size % r == 0 and size // r >= H] or [0])
            im = Image.new('L', (max(1, rowb * 4), H))
            px = im.load()
            for y in range(H):
                for xb in range(rowb):
                    v = d[offs[i] + y * rowb + xb]
                    for k in range(4):
                        px[4 * xb + k, y] = ((v >> (2 * k)) & 3) * 85
            self.img.append(im)


def main():
    sim = json.load(open(os.path.join(SDK, 'Devices', 'venu2', 'simulator.json')))
    ww = next(s for s in sim['fonts'] if s['fontSet'] == 'ww')
    files = {e['name']: e['filename'] for e in ww['fonts']}
    out = {}
    for name in NAMES:
        c = CFT(os.path.join(SDK, 'Fonts', files[name] + '.cft'))
        # one-row atlas: white glyphs, grey value as alpha
        xs, ws, x = [], [], 0
        for g in c.img:
            xs.append(x); ws.append(g.width); x += g.width
        atlas = Image.new('RGBA', (max(1, x), c.height), (255, 255, 255, 0))
        for g, gx in zip(c.img, xs):
            tile = Image.new('RGBA', g.size, (255, 255, 255, 0))
            tile.putalpha(g)
            atlas.paste(tile, (gx, 0))
        b = io.BytesIO()
        atlas.save(b, 'PNG', optimize=True)
        out[name] = {'height': c.height, 'ascent': c.ascent, 'ranges': c.ranges, 'adv': c.adv,
                     'x': xs, 'w': ws, 'src': 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()}
        print(name, files[name], 'height', c.height, 'glyphs', len(c.adv))
    with open(OUT, 'w') as fh:
        fh.write('// Garmin Venu 2 system fonts, generated by make_fonts.py from the local Connect IQ SDK.\n'
                 '// Garmin font data: do not commit (see .gitignore).\nconst VFONTS = ' + json.dumps(out) + ';\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
